#!/usr/bin/env python3
"""Write web/examples.js: a few dev fixtures as examples for the browser page."""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PICK = [
    ("dev-a-01", "Emoji before the entity: UTF-16 offsets declared as code points", "رمز تعبيري قبل الكيان: مواضع UTF-16 معلنة كنقاط ترميز"),
    ("dev-c-01", "Alef + combining hamza: offsets from the NFC text", "ألف مع همزة مركّبة: مواضع من النص بعد NFC"),
    ("dev-d-01", "Lam-alef ligature: offsets from the NFKC text", "حرف لام ألف المدمج: مواضع من النص بعد NFKC"),
    ("dev-e-01", "Span ends before the last haraka", "امتداد ينتهي قبل الحركة الأخيرة"),
    ("dev-f-01", "Offsets counted after tatweel removal", "مواضع محسوبة بعد حذف التطويل"),
    ("dev-h-02", "Clitic policy exclude: span starts with و", "سياسة السوابق exclude: امتداد يبدأ بالواو"),
    ("dev-n-01", "CRLF text, offsets counted with LF", "نص بفواصل CRLF ومواضع محسوبة بفاصل LF"),
    ("dev-m-02", "CoNLL IOB2: I-LOC after B-PER", "CoNLL بمخطط IOB2: الوسم I-LOC بعد B-PER"),
    ("dev-q-01", "Arabic comma inside the span", "فاصلة عربية داخل الامتداد"),
    ("dev-r-02", "Left-to-right marks around a Latin name", "علامات اتجاه حول اسم لاتيني"),
    ("dev-v-03", "A valid Label Studio export", "تصدير سليم من Label Studio"),
]
fx = {}
with open(os.path.join(ROOT, "fixtures", "dev", "fixtures.jsonl"), encoding="utf-8") as fh:
    for line in fh:
        f = json.loads(line)
        fx[f["fixture_id"]] = f
out = []
for fid, en, ar in PICK:
    f = fx[fid]
    opts = dict(f["options"])
    out.append({"id": fid, "title_en": en, "title_ar": ar, "format": f["format"], "options": opts, "payload": f["input_payload"]})
with open(os.path.join(ROOT, "web", "examples.js"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write("// Generated by scripts/build_web_examples.py from fixtures/dev/fixtures.jsonl (CC BY 4.0). Do not edit.\n")
    fh.write("export const EXAMPLES = %s;\n" % json.dumps(out, ensure_ascii=True, indent=1))
print(len(out))
