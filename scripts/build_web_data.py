#!/usr/bin/env python3
"""Write web/codes.js from the package data, so the browser port uses the same messages as the
Python package."""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "src", "arabic_ner_validator", "data")
for name, var in (("codes.json", "CODES"),):
    with open(os.path.join(D, name), encoding="utf-8") as fh:
        data = json.load(fh)
    out = os.path.join(ROOT, "web", name.replace(".json", ".js"))
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("// Generated by scripts/build_web_data.py from src/arabic_ner_validator/data/%s. Do not edit.\n" % name)
        fh.write("export const %s = %s;\n" % (var, json.dumps(data, ensure_ascii=False, indent=1)))
print("ok")
